const AUTHOR_NAMES = { lorc: 'Lorc', delapouite: 'Delapouite', skoll: 'Skoll', 'carl-olsen': 'Carl Olsen', 'john-colburn': 'John Colburn', sbed: 'Sbed', cathelineau: 'Cathelineau', caro_asercion: 'Caro Asercion', 'caro-asercion': 'Caro Asercion', viscious_speed: 'Viscious Speed', 'viscious-speed': 'Viscious Speed', faithtoken: 'Faithtoken', heavenlydog: 'HeavenlyDog', lucasms: 'Lucas', 'lord-berandas': 'Lord Berandas', irongamer: 'Irongamer', felbrigg: 'Felbrigg', 'john-redman': 'John Redman', priorblue: 'PriorBlue', willdabeast: 'Willdabeast', zeromancer: 'Zeromancer', darkzaitzev: 'DarkZaitzev', spencerdub: 'SpencerDub', generalace135: 'GeneralAce135', zajkonur: 'Zajkonur', catsu: 'Catsu', starseeker: 'Starseeker', 'pepijn-poolman': 'Pepijn Poolman', 'pierre-leducq': 'Pierre Leducq', andymeneely: 'Andy Meneely', aussiesim: 'Aussiesim', sparker: 'Sparker', rihlsul: 'Rihlsul', quoting: 'Quoting', guard13007: 'Guard13007', kier_heyl: 'Kier Heyl', 'kier-heyl': 'Kier Heyl', seregacthtuf: 'SeregaCthtuf' };

const set = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules/@iconify-json/game-icons/icons.json'), 'utf8'));
const treePath = process.argv[2];
const authorOf = {};
if (treePath) {
  for (const t of JSON.parse(fs.readFileSync(treePath, 'utf8')).tree) {
    const m = /^([^/]+)\/(?:.*\/)?([^/]+)\.svg$/.exec(t.path);
    if (m) authorOf[m[2]] ??= AUTHOR_NAMES[m[1]] ?? m[1];
  }
} else if (fs.existsSync(OUT)) {
  for (const m of fs.readFileSync(OUT, 'utf8').matchAll(/'([a-z0-9-]+)': \{ author: '([^']+)'/g)) authorOf[m[1]] = m[2];
}

const icons = {};
for (const [id, name] of Object.entries(MAP)) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`game-icons has no "${name}" (for ${id})`);
  icons[name] = { author: authorOf[name] ?? 'game-icons.net', body: icon.body.replace(/fill="currentColor"/g, '') };
}

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
let ts = `// GENERATED by scripts/gen-monster-icons.mjs — do not edit by hand.\n// Monster art from game-icons.net, CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/). See CREDITS.md.\n\n`;
ts += `export const ICONS: Record<string, { author: string; body: string }> = {\n`;
for (const [name, v] of Object.entries(icons)) ts += `  '${name}': { author: '${esc(v.author)}', body: '${esc(v.body)}' },\n`;
ts += `};\n\nexport const MONSTER_ICON: Record<string, string> = ${JSON.stringify(MAP, null, 2).replace(/"/g, "'")};\n`;
fs.writeFileSync(OUT, ts);

const byAuthor = {};
for (const [name, v] of Object.entries(icons)) (byAuthor[v.author] ??= []).push(name);
let md = `# Credits\n\n## Monster art\n\nMonster icons from [game-icons.net](https://game-icons.net), licensed under [CC BY 3.0](https://creativecommons.org/licenses/by/3.0/). Recoloured and framed for the game.\n\n`;
for (const [a, list] of Object.entries(byAuthor).sort()) md += `- Icons made by **${a}**: ${list.sort().join(', ')}\n`;
md += `\n## Fonts\n\n- [Young Serif](https://github.com/noirblancrouge/YoungSerif) by Bastien Sozeau — SIL Open Font License 1.1\n- [Merriweather](https://github.com/SorkinType/Merriweather) by Sorkin Type — SIL Open Font License 1.1\n`;
fs.writeFileSync(path.join(ROOT, 'CREDITS.md'), md);
console.log(`${Object.keys(icons).length} icons for ${Object.keys(MAP).length} monsters → ${path.relative(ROOT, OUT)}`);
